test('--pin-defaults only emits statements for postgres; other grantors get a comment, not a statement', () => {
  const findings = [
    ...LEGACY,
    { kind: 'legacy_default_privileges', table: null, grantorRole: 'supabase_admin', objectType: 'tables', grants: [{ grantee: 'anon', privileges: ['SELECT'] }] },
  ];
  const plan = buildLeastPrivilegePlan(findings, { now: NOW, pinDefaults: true });
  const statements = plan.migrationSql.split('\n').filter(l => l.startsWith('alter default privileges'));
  assert.equal(statements.length, 3);
  assert.ok(statements.every(l => l.startsWith('alter default privileges for role postgres in schema public revoke all on ')));
  assert.match(plan.migrationSql, /-- Legacy default privileges also exist for supabase_admin/);
  assert.doesNotMatch(plan.rollbackSql, /supabase_admin/);
});

test('the plan never revokes SELECT from a role with a write policy on that table', () => {
  const findings = [
    { kind: 'grant_without_policy', table: 'public.orders', role: 'authenticated', privilege: 'SELECT' },
    { kind: 'grant_without_policy', table: 'public.orders', role: 'authenticated', privilege: 'DELETE' },
    { kind: 'write_without_select_policy', table: 'public.orders', role: 'authenticated' },
  ];
  const plan = buildLeastPrivilegePlan(findings, { now: NOW });
  assert.match(plan.migrationSql, /^revoke delete on public\.orders from authenticated;$/m);
  assert.doesNotMatch(plan.migrationSql, /revoke[^;]*select[^;]*from authenticated/);
});
